import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createJiti } from "jiti";
import { isolateGuardEnv } from "./test/env.mjs";
isolateGuardEnv();
const jiti = createJiti(import.meta.url);
const sbx = jiti("../extensions/sandbox/index.ts");
const fixture = mkdtempSync(join(tmpdir(), "sbx-"));
writeFileSync(join(fixture, ".sandbox"), "dev\n");
const handlers = {};
sbx.default({ registerFlag(){}, registerCommand(){}, on(n,h){handlers[n]=h;}, getFlag:()=>undefined });
const ev = { toolName: "bash", input: { command: "echo hello" } };
await handlers.tool_call(ev, { cwd: fixture, ui: { notify(){} }, hasUI: false });
console.log(JSON.stringify(ev.input.command).slice(0, 700));
rmSync(fixture, { recursive: true, force: true });
